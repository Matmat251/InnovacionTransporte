-- Migración V2: Dominio operativo completo (identidad, flota, viajes, ventas idempotentes, encomiendas, clima, alertas, riesgo y contingencias)
-- Incluye datos semilla ficticios para la demo de aceptación Lima-Huancayo.

CREATE TABLE passengers (
    id UUID PRIMARY KEY,
    document_type VARCHAR(16) NOT NULL CHECK (document_type IN ('DNI', 'CE', 'PASAPORTE')),
    document_number VARCHAR(20) NOT NULL UNIQUE,
    full_name VARCHAR(150) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE buses (
    id UUID PRIMARY KEY,
    company_id UUID NOT NULL REFERENCES companies(id),
    plate VARCHAR(16) NOT NULL UNIQUE,
    model VARCHAR(80) NOT NULL,
    seat_capacity INTEGER NOT NULL CHECK (seat_capacity > 0),
    enabled_seats INTEGER NOT NULL CHECK (enabled_seats > 0),
    cargo_capacity_kg NUMERIC(10, 2) NOT NULL CHECK (cargo_capacity_kg >= 0),
    current_terminal_code VARCHAR(24) NOT NULL REFERENCES terminals(code),
    status VARCHAR(24) NOT NULL CHECK (status IN ('DISPONIBLE', 'EN_SERVICIO', 'MANTENIMIENTO')),
    turnaround_minutes INTEGER NOT NULL DEFAULT 20 CHECK (turnaround_minutes >= 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE trips (
    id UUID PRIMARY KEY,
    route_id UUID NOT NULL REFERENCES routes(id),
    bus_id UUID NOT NULL REFERENCES buses(id),
    origin_terminal_code VARCHAR(24) NOT NULL REFERENCES terminals(code),
    destination_terminal_code VARCHAR(24) NOT NULL REFERENCES terminals(code),
    original_departure_utc TIMESTAMP WITH TIME ZONE NOT NULL,
    original_arrival_utc TIMESTAMP WITH TIME ZONE NOT NULL,
    scheduled_departure_utc TIMESTAMP WITH TIME ZONE NOT NULL,
    scheduled_arrival_utc TIMESTAMP WITH TIME ZONE NOT NULL,
    actual_departure_utc TIMESTAMP WITH TIME ZONE,
    actual_arrival_utc TIMESTAMP WITH TIME ZONE,
    turnaround_minutes INTEGER NOT NULL DEFAULT 20,
    base_fare_pen NUMERIC(10, 2) NOT NULL CHECK (base_fare_pen > 0),
    status VARCHAR(24) NOT NULL CHECK (status IN ('PROGRAMADO', 'EN_CURSO', 'COMPLETADO', 'REPROGRAMADO', 'CANCELADO')),
    incident_notes VARCHAR(500),
    previous_trip_id UUID REFERENCES trips(id),
    version INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE trip_seats (
    id UUID PRIMARY KEY,
    trip_id UUID NOT NULL REFERENCES trips(id),
    seat_number INTEGER NOT NULL CHECK (seat_number > 0),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    status VARCHAR(24) NOT NULL CHECK (status IN ('DISPONIBLE', 'VENDIDO', 'BLOQUEADO')),
    active_ticket_id UUID,
    UNIQUE (trip_id, seat_number)
);

CREATE TABLE sales (
    id UUID PRIMARY KEY,
    trip_id UUID NOT NULL REFERENCES trips(id),
    passenger_id UUID NOT NULL REFERENCES passengers(id),
    seat_number INTEGER NOT NULL,
    amount_pen NUMERIC(10, 2) NOT NULL CHECK (amount_pen >= 0),
    status VARCHAR(24) NOT NULL CHECK (status IN ('VIGENTE', 'ANULADA')),
    idempotency_key VARCHAR(120) NOT NULL UNIQUE,
    payload_hash VARCHAR(64) NOT NULL,
    sold_by VARCHAR(64) NOT NULL,
    cancelled_by VARCHAR(64),
    cancel_reason VARCHAR(300),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancelled_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE tickets (
    id UUID PRIMARY KEY,
    sale_id UUID NOT NULL UNIQUE REFERENCES sales(id),
    trip_id UUID NOT NULL REFERENCES trips(id),
    passenger_id UUID NOT NULL REFERENCES passengers(id),
    seat_number INTEGER NOT NULL,
    ticket_code VARCHAR(40) NOT NULL UNIQUE,
    amount_pen NUMERIC(10, 2) NOT NULL,
    status VARCHAR(24) NOT NULL CHECK (status IN ('EMITIDO', 'ANULADO')),
    active_seat_lock VARCHAR(80) UNIQUE,
    issued_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE parcels (
    id UUID PRIMARY KEY,
    tracking_code VARCHAR(40) NOT NULL UNIQUE,
    route_id UUID NOT NULL REFERENCES routes(id),
    trip_id UUID NOT NULL REFERENCES trips(id),
    sender_name VARCHAR(150) NOT NULL,
    recipient_name VARCHAR(150) NOT NULL,
    origin_terminal_code VARCHAR(24) NOT NULL REFERENCES terminals(code),
    destination_terminal_code VARCHAR(24) NOT NULL REFERENCES terminals(code),
    weight_kg NUMERIC(10, 2) NOT NULL CHECK (weight_kg > 0),
    amount_pen NUMERIC(10, 2) NOT NULL CHECK (amount_pen >= 0),
    status VARCHAR(24) NOT NULL CHECK (status IN ('RECIBIDA', 'EN_TRANSPORTE', 'ENTREGADA')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE parcel_status_history (
    id UUID PRIMARY KEY,
    parcel_id UUID NOT NULL REFERENCES parcels(id),
    from_status VARCHAR(24),
    to_status VARCHAR(24) NOT NULL CHECK (to_status IN ('RECIBIDA', 'EN_TRANSPORTE', 'ENTREGADA')),
    actor_username VARCHAR(64) NOT NULL,
    notes VARCHAR(300),
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE weather_observations (
    id UUID PRIMARY KEY,
    trip_id UUID NOT NULL REFERENCES trips(id),
    segment_id UUID NOT NULL REFERENCES route_segments(id),
    source VARCHAR(48) NOT NULL,
    latitude NUMERIC(9, 6) NOT NULL,
    longitude NUMERIC(9, 6) NOT NULL,
    valid_at_utc TIMESTAMP WITH TIME ZONE NOT NULL,
    fetched_at_utc TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at_utc TIMESTAMP WITH TIME ZONE NOT NULL,
    precipitation_mm NUMERIC(6, 2),
    precipitation_prob_pct INTEGER,
    temperature_c NUMERIC(5, 2),
    wind_kmh NUMERIC(6, 2),
    visibility_m INTEGER,
    weather_code INTEGER,
    units VARCHAR(64) NOT NULL,
    data_status VARCHAR(32) NOT NULL CHECK (data_status IN ('VIGENTE', 'DEMO', 'INFORMACION_INSUFICIENTE', 'VENCIDO'))
);

CREATE TABLE road_alerts (
    id UUID PRIMARY KEY,
    segment_id UUID NOT NULL REFERENCES route_segments(id),
    source_name VARCHAR(48) NOT NULL,
    reference_url VARCHAR(300),
    status VARCHAR(32) NOT NULL CHECK (status IN ('DESPEJADO', 'TRANSITO_RESTRINGIDO', 'CERRADO')),
    origin_type VARCHAR(24) NOT NULL CHECK (origin_type IN ('OFICIAL_MANUAL', 'SIMULADA')),
    description VARCHAR(400),
    checked_at_utc TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    valid_until_utc TIMESTAMP WITH TIME ZONE NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by VARCHAR(64) NOT NULL
);

CREATE TABLE risk_assessments (
    id UUID PRIMARY KEY,
    trip_id UUID NOT NULL REFERENCES trips(id),
    threshold_minutes INTEGER NOT NULL,
    model_version VARCHAR(64) NOT NULL,
    mode VARCHAR(16) NOT NULL CHECK (mode IN ('DEMO', 'REAL')),
    status VARCHAR(32) NOT NULL CHECK (status IN ('OK', 'INFORMACION_INSUFICIENTE')),
    delay_probability NUMERIC(6, 4),
    calibrated BOOLEAN NOT NULL DEFAULT FALSE,
    risk_level VARCHAR(32) NOT NULL CHECK (risk_level IN ('BAJO', 'MEDIO', 'ALTO', 'INFORMACION_INSUFICIENTE')),
    missing_features VARCHAR(300),
    latency_ms NUMERIC(10, 2) NOT NULL DEFAULT 0,
    evaluated_at_utc TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE contingency_simulations (
    id UUID PRIMARY KEY,
    initial_trip_id UUID NOT NULL REFERENCES trips(id),
    affected_trip_id UUID REFERENCES trips(id),
    trip_version INTEGER NOT NULL,
    risk_level VARCHAR(32) NOT NULL,
    margin_minutes INTEGER,
    delay_30_ready_utc TIMESTAMP WITH TIME ZONE,
    delay_30_lost_minutes INTEGER,
    delay_60_ready_utc TIMESTAMP WITH TIME ZONE,
    delay_60_lost_minutes INTEGER,
    options_json VARCHAR(4000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE contingency_decisions (
    id UUID PRIMARY KEY,
    simulation_id UUID NOT NULL REFERENCES contingency_simulations(id),
    initial_trip_id UUID NOT NULL REFERENCES trips(id),
    affected_trip_id UUID REFERENCES trips(id),
    action_type VARCHAR(32) NOT NULL CHECK (action_type IN ('MANTENER_PLAN', 'ASIGNAR_BUS_RESERVA', 'REPROGRAMAR')),
    previous_bus_id UUID REFERENCES buses(id),
    assigned_bus_id UUID REFERENCES buses(id),
    new_departure_utc TIMESTAMP WITH TIME ZONE,
    reassigned_tickets INTEGER NOT NULL DEFAULT 0,
    reassigned_parcels INTEGER NOT NULL DEFAULT 0,
    rationale VARCHAR(500) NOT NULL,
    decided_by VARCHAR(64) NOT NULL,
    decided_at_utc TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_trips_bus_departure ON trips(bus_id, scheduled_departure_utc);
CREATE INDEX idx_sales_trip_status ON sales(trip_id, status);
CREATE INDEX idx_parcels_trip_status ON parcels(trip_id, status);
CREATE INDEX idx_weather_trip_fetched ON weather_observations(trip_id, fetched_at_utc DESC);
CREATE INDEX idx_road_alerts_segment_active ON road_alerts(segment_id, active, valid_until_utc);

